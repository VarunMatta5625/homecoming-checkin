#!/usr/bin/env bash
# Builds supabase/setup_all.sql (all migrations, then the fake seed data) for a NEW Supabase project.
#
#   scripts/build_setup_all.sh          rewrite supabase/setup_all.sql
#   scripts/build_setup_all.sh --check  fail if the committed file is out of date (CI runs this)
set -euo pipefail
cd "$(dirname "$0")/../supabase"

build() {
  echo "-- Homecoming 2026 check-in: full setup for a NEW, empty Supabase project (schema + security + RPCs + FAKE test data)."
  echo "-- Generated by concatenating supabase/migrations/*.sql and supabase/seed_dev.sql. Run once."
  for f in migrations/*.sql seed_dev.sql; do
    echo
    echo "-- ===== $f ====="
    cat "$f"
  done
}

if [ "${1:-}" = "--check" ]; then
  if build | diff -q - setup_all.sql >/dev/null; then echo "setup_all.sql is up to date"; else
    echo "supabase/setup_all.sql is out of date. Run scripts/build_setup_all.sh and commit the result." >&2; exit 1
  fi
else
  build > setup_all.sql
  echo "wrote supabase/setup_all.sql"
fi
